// Países en los que puede estar un aviso, y de los que puede ser quien mira.
//
// Son los 249 de la ISO 3166-1, y el archivo lo genera
// `scripts/generar-paises.mjs`: NO se edita a mano. Antes eran 26 elegidos a
// dedo más un "Otro país", y eso ya se rompió en producción — el mapa deduce el
// país del punto y guardaba códigos que el selector no sabía enseñar (tres
// avisos de Bucarest quedaron repartidos entre "RO" y "Otro país", y por
// Rumanía no se podía ni filtrar).
//
// El `code` es ISO-3166-1 alpha-2, que es lo que entienden tanto Google Maps
// (`components=country:PE`) como el catálogo 06 de SUNAT para el comprobante de
// un extranjero.
//
// `zonas` y `centro` solo los llevan los países donde de verdad hay gente
// nuestra: son datos escritos a mano y solo hacen falta para adivinar de dónde
// mira alguien (sin pedirle permiso de ubicación: el navegador ya sabe su zona
// horaria) y para recentrar el mapa. Para el resto, el mapa se recentra
// buscando el país con el geocoder.

export interface Pais {
  /** ISO-3166-1 alpha-2. */
  code: string;
  nombre: string;
  /** Zonas horarias IANA. Solo en los países con presencia conocida. */
  zonas?: string[];
  /** Centro aproximado, para recentrar el mapa al cambiar de país. */
  centro?: { lat: number; lng: number };
}

